/** Shown for a name with no mapping, instead of crashing. */
export const TABLER_FALLBACK_ICON: TablerIcon = IconCircleDashed

/** The Tabler icon for a `web` icon name (filled twin when asked and present). */
export function tablerIconFor(
	name: WebIconName,
	variant?: 'filled' | 'outlined'
): TablerIcon {
	if (!Object.hasOwn(TABLER_ICONS, name)) return TABLER_FALLBACK_ICON
	if (variant === 'filled') {
		const filled = TABLER_FILLED_ICONS[name]
		if (filled != null) return filled
	}
	return TABLER_ICONS[name]
}
